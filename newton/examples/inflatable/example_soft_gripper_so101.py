@wp.kernel
def _xform_points_by_transform(
    points_in: wp.array(dtype=wp.vec3),
    tf: wp.transform,
    points_out: wp.array(dtype=wp.vec3),
):
    """Apply a single rigid transform to every input point.

    Used per substep to map FEM keypoints from the soft body's local
    frame (origin) to the world cylinder-tip pose, before handing them
    to :meth:`FingerCapsuleColliders.update_endpoints`.
    """
    tid = wp.tid()
    points_out[tid] = wp.transform_point(tf, points_in[tid])


@wp.kernel
def _xform_points_by_transform_arr(
    points_in: wp.array(dtype=wp.vec3),
    tf_arr: wp.array(dtype=wp.transform),
    points_out: wp.array(dtype=wp.vec3),
):
    """Same as :func:`_xform_points_by_transform` but reads the transform
    from a length-1 device array. Required inside ScopedCapture: the
    cylinder-tip transform changes each substep because state_0.body_q
    is updated by MuJoCo, so it can't be a captured scalar kernel arg —
    we recompute it on-device with :func:`_compute_cyl_tip_xform_kernel`
    and the points kernel just reads ``tf_arr[0]``.
    """
    tid = wp.tid()
    points_out[tid] = wp.transform_point(tf_arr[0], points_in[tid])


@wp.kernel
def _compute_cyl_tip_xform_kernel(
    body_q: wp.array(dtype=wp.transform),
    wrist_idx: wp.int32,
    stem_tip_local: wp.vec3,
    body_pos: wp.vec3,
    tf_out: wp.array(dtype=wp.transform),
):
    """Compose the FEM→cylinder-tip transform on device.

    Mirrors the host-side :meth:`Example._current_cylinder_tip_xform`
    but reads ``state_0.body_q[wrist_idx]`` directly without copying to
    host, so the whole substep loop stays capture-safe. Writes one
    ``wp.transform`` into ``tf_out[0]``; the points-transform kernel
    above reads from the same slot.
    """
    if wp.tid() != 0:
        return
    wrist_tf = body_q[wrist_idx]
    stem_offset = wp.transform(stem_tip_local, wp.quat_identity())
    cyl_tip_world = wp.transform_multiply(wrist_tf, stem_offset)
    inv_body = wp.transform(-body_pos, wp.quat_identity())
    tf_out[0] = wp.transform_multiply(cyl_tip_world, inv_body)


