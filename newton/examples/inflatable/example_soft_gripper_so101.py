    def _set_capsules_visible(self, visible: bool) -> None:
        """Flip the ``VISIBLE`` flag on every capsule shape's render batch.

        Same pattern example_inflatable_gripper uses to hide its rigid
        stem shape (see _set_hub_visible there). The Newton GL viewer
        reads ``shapes.flags`` per batch every frame and gates rendering
        on the ``VISIBLE`` bit, so mutating the bit on each capsule
        batch hides/shows just the capsule shapes without affecting the
        soft mesh, ground, or rigid_objects. No-op when the viewer
        backend doesn't expose ``_shape_to_batch`` or when capsule
        registration was skipped.
        """
        if not self._capsule_shape_ids:
            return
        shape_to_batch = getattr(self.viewer, "_shape_to_batch", None)
        if shape_to_batch is None:
            return
        visible_bit = int(newton.ShapeFlags.VISIBLE)
        for sid in self._capsule_shape_ids:
            sid = int(sid)
            if sid < 0 or sid >= len(shape_to_batch):
                continue
            batch = shape_to_batch[sid]
            if batch is None:
                continue
            if visible:
                batch.flags |= visible_bit
            else:
                batch.flags &= ~visible_bit

    def _compute_mirror_transform(self) -> wp.transform:
        """Build the transform mapping an FEM particle from its physical
        position (anchored at ``body_position``) to its mirror-pose
        world position, given the 6 DOF slider state: 3 translation
        floats + 3 euler floats (radians, XYZ-extrinsic).

        We rotate the gripper around the **mirror's hub**, not around
        the world origin — so dragging the rotation sliders spins the
        mirror in place. Returns a ``wp.transform`` consumed by:

        * the captured substep loop via ``_cyl_tip_tf_buf`` (written
          here once per frame by the host preamble in :meth:`step` when
          arm mode is OFF), and
        * the per-frame side-mirror render in :meth:`render`.

        Host-only helper — cannot run inside ScopedCapture because it
        reads transient numpy slider state.
        """
        bp = np.asarray(self._body_position, dtype=np.float64)
        mt = np.asarray(self._slider_pos, dtype=np.float64)
        mirror_hub_world = bp + mt
        r2, p2, y2 = (0.5 * a for a in self._slider_euler)
        cr, sr = np.cos(r2), np.sin(r2)
        cp, sp = np.cos(p2), np.sin(p2)
        cy, sy = np.cos(y2), np.sin(y2)
        # XYZ-extrinsic: q = q_z · q_y · q_x → (qw, qx, qy, qz).
        qw = cr * cp * cy - sr * sp * sy
        qx = sr * cp * cy + cr * sp * sy
        qy = cr * sp * cy - sr * cp * sy
        qz = cr * cp * sy + sr * sp * cy
        xx, yy, zz = qx * qx, qy * qy, qz * qz
        xy, xz, yz = qx * qy, qx * qz, qy * qz
        wx, wy, wz = qw * qx, qw * qy, qw * qz
        R = np.array([
            [1.0 - 2.0 * (yy + zz), 2.0 * (xy - wz),       2.0 * (xz + wy)],
            [2.0 * (xy + wz),       1.0 - 2.0 * (xx + zz), 2.0 * (yz - wx)],
            [2.0 * (xz - wy),       2.0 * (yz + wx),       1.0 - 2.0 * (xx + yy)],
        ], dtype=np.float64)
        t = mirror_hub_world - (R @ bp)
        return wp.transform(
            wp.vec3(float(t[0]), float(t[1]), float(t[2])),
            wp.quat(float(qx), float(qy), float(qz), float(qw)),
        )

    def _current_cylinder_tip_xform(self) -> wp.transform:
        """Build the transform mapping an FEM particle (anchored at
        ``body_position`` in its own local frame) to its corresponding
        world position at the SO-101's cylinder tip.

        Composes three pieces:
            T = wrist_world ∘ stem_tip_local ∘ inv(translate(body_pos))

        Read left→right: first translate the FEM particle by
        ``-body_pos`` so the hub sits at the local origin, then place it
        at the stem tip in wrist-local coords, then promote to world via
        the live MuJoCo-integrated wrist pose. Drives both per-substep
        capsule keypoints and per-frame triangle rendering — 6 DOF for
        the gripper comes from the SO-101 IK / sliders, not from
        widgets on this gripper.
        """
        wrist_row = self.state_0.body_q.numpy()[self.wrist_body_id]
        wrist_q = wp.quat(
            float(wrist_row[3]), float(wrist_row[4]),
            float(wrist_row[5]), float(wrist_row[6]),
        )
        wrist_tf = wp.transform(
            wp.vec3(float(wrist_row[0]), float(wrist_row[1]), float(wrist_row[2])),
            wrist_q,
        )
        cyl_tip_world = wp.transform_multiply(
            wrist_tf, wp.transform(STEM_TIP_LOCAL, wp.quat_identity())
        )
        inv_body = wp.transform(
            wp.vec3(
                -self._body_position[0],
                -self._body_position[1],
                -self._body_position[2],
            ),
            wp.quat_identity(),
        )
        return wp.transform_multiply(cyl_tip_world, inv_body)

