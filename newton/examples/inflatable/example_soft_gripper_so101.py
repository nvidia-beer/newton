# Example Soft Gripper SO-101 (kinematics-only proxy)
#
# Three valid modes, selected by the orthogonal ``--arm`` / ``--soft``
# CLI flags (both default True). ``--no-arm --no-soft`` is forbidden.
#
#   • ``--arm --soft`` (default) — full SO-101 + chambered FEM gripper +
#     kinematic capsules. The canonical example described below.
#   • ``--arm --no-soft`` — rigid-only SO-101 + IK + dynamic rigid_objects.
#     Inflation/pressure widgets are placeholders for future soft work.
#   • ``--no-arm --soft`` — chambered FEM gripper alone, anchored by a
#     Dirichlet pin on the hub, with 6-DOF mirror pose sliders driving a
#     render-only copy at a configurable offset. NaN/drift readouts
#     surface stability failures. Real -Z gravity on the soft body.
#
# Arm+soft mode (canonical):
#
# Rigid SO-101 manipulator + position IK + dynamic rigid_objects (MuJoCo)
# with a **decoupled** chambered soft FEM gripper driving rigid capsule
# colliders at the stem tip. The soft body is a kinematics generator
# only — its physics is NOT coupled to MuJoCo:
#
#  • The FEM lives at world origin and is anchored by zeroing
#    ``particle_inv_mass`` on the hub particles (no Dirichlet pin
#    bookkeeping, no glue solver). Gravity is zeroed on the inflatable
#    solver so the body holds its rest pose unless inflated.
#  • ``SolverInflatable`` runs with ``use_constraint_contacts=False`` and
#    ``ground_plane=None`` — the soft body never sees rigid contacts.
#  • Each substep: read FEM keypoints from particle_q (in soft-local),
#    transform them by the current cylinder-tip pose, then drive the
#    kinematic capsule bodies in the MuJoCo scene. MuJoCo steps arm +
#    rigid_objects + capsules; capsules are the *only* way the soft
#    deformation affects the rigid world (no forces, just kinematics).
#  • For rendering, the same transform is applied to the soft body's
#    triangle vertices so the gripper appears at the cylinder tip.
#
#  • IK runs on a slim arm-only model — drag the gizmo at the stem tip
#    to retarget; the IK solution is written as the position target.
#  • Per-finger pressure sliders drive ``set_chamber_pressures`` on the
#    inflatable solver; fingers curl/extend; capsules follow.
#  • Optional dynamic rigid objects (sphere / box) are spawned from the
#    JSON ``rigid-objects`` block for the gripper to grasp.
#
# Asset sources:
#   • SO-ARM101-10x-stem.usd  — rigid SO-101 (scaled 10×) + stem cylinder
#   • gripper_4f.usda (or any compatible chambered gripper) — soft FEM
#     body with chambers, springs, finger skeletons, and hub glue_pairs
#     (the soft particle indices anchored to the cylinder tip).
#
# Command: python -m newton.examples soft_gripper_so101
