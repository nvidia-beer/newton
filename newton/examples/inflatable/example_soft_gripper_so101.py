def _joint_name_matches(jname: str, name: str) -> bool:
    """Exact last-path-segment match between a USD joint label and a config name."""
    return jname.split("/")[-1] == name


def _apply_pose_and_limits(
    builder: newton.ModelBuilder,
    default_joint_q: dict[str, float] | None = None,
    safe_joint_limits: dict[str, tuple[float, float]] | None = None,
    joint_actuator_gains: dict[str, tuple[float, float, float]] | None = None,
) -> None:
    """Write the configured pose / limits / PD-actuator gains into the builder."""
    defaults = default_joint_q if default_joint_q is not None else SO101_DEFAULT_JOINT_Q
    limits = safe_joint_limits if safe_joint_limits is not None else SO101_SAFE_JOINT_LIMITS
    gains = joint_actuator_gains or {}
    for j, jname in enumerate(builder.joint_label):
        q_idx = builder.joint_q_start[j]
        dof_idx = builder.joint_qd_start[j]
        for name, q in defaults.items():
            if _joint_name_matches(jname, name):
                builder.joint_q[q_idx] = q
                if name in limits:
                    lo, hi = limits[name]
                    builder.joint_limit_lower[dof_idx] = lo
                    builder.joint_limit_upper[dof_idx] = hi
                if name in gains:
                    ke, kd, eff = gains[name]
                    builder.joint_target_mode[dof_idx] = int(newton.JointTargetMode.POSITION)
                    builder.joint_target_ke[dof_idx] = float(ke)
                    builder.joint_target_kd[dof_idx] = float(kd)
                    builder.joint_target_pos[dof_idx] = float(q)
                    builder.joint_effort_limit[dof_idx] = float(eff)
                break


def _find_body_index(model_or_builder, name: str) -> int:
    """Find a body whose label endswith / contains ``name`` (case-insensitive)."""
    labels = list(model_or_builder.body_label)
    name_lc = name.lower()
    for i, label in enumerate(labels):
        if label.lower().endswith(name_lc) or name_lc in label.lower():
            return i
    raise KeyError(f"no body matching {name!r} in {labels}")


