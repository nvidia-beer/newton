    def step(self):
        """Per-frame host preamble + capture_launch (or eager fallback).

        Everything that involves a host↔device sync (IK on the slim
        arm model, slider state read, pressure ramp, joint_target_pos
        write, chamber-pressure upload, mirror-pose composition) lives
        HERE — they can't run inside the captured graph because they
        reference transient numpy buffers / Python state. The captured
        graph replays only the pure-device substep loop in
        :meth:`simulate`.
        """
        # 1) Arm path — IK or sliders → arm joint_q target. (Host)
        if self._arm_enabled:
            if self._use_ik:
                self.pos_obj.set_target_position(0, wp.transform_get_translation(self.ee_tf))
                self.ik_solver.step(self.ik_joint_q, self.ik_joint_q, iterations=self.ik_iters)
                arm_q_now = self.arm_model.joint_q.numpy()
                for name, q_idx in self._joint_q_idx.items():
                    self._joint_q_targets[name] = float(arm_q_now[q_idx])
            else:
                arm_q_new = self.arm_model.joint_q.numpy()
                for name, q_idx in self._joint_q_idx.items():
                    arm_q_new[q_idx] = float(self._joint_q_targets[name])
                self.arm_model.joint_q.assign(arm_q_new)
                newton.eval_fk(
                    self.arm_model,
                    self.arm_model.joint_q,
                    self.arm_model.joint_qd,
                    self.arm_state,
                )
                ee_row = self.arm_state.body_q.numpy()[self._arm_wrist_idx]
                arm_wrist_xform = wp.transform(
                    wp.vec3(float(ee_row[0]), float(ee_row[1]), float(ee_row[2])),
                    wp.quat(float(ee_row[3]), float(ee_row[4]),
                            float(ee_row[5]), float(ee_row[6])),
                )
                self.ee_tf = wp.transform_multiply(
                    arm_wrist_xform,
                    wp.transform(STEM_TIP_LOCAL, wp.quat_identity()),
                )

            # 2) MuJoCo PD target write. (Host)
            arm_q = self.arm_model.joint_q.numpy()
            tgt = self.control.joint_target_pos.numpy()
            tgt[: self._arm_q_count] = arm_q
            self.control.joint_target_pos.assign(tgt)
        elif self._soft_enabled and self._cyl_tip_tf_buf is not None:
            # Mirror mode: compose the slider-driven 6-DOF mirror
            # transform on host and stash it in the device buffer the
            # captured substep loop reads. Within a frame the mirror
            # pose is constant (sliders don't move between substeps),
            # so a single host→device write per frame suffices and the
            # rest of the substep loop stays capture-safe.
            mirror_tf = self._compute_mirror_transform()
            src = wp.array(
                [mirror_tf], dtype=wp.transform, device=self.model.device
            )
            wp.copy(self._cyl_tip_tf_buf, src)

        # 3) Chamber pressure ramp (rate-limited chase). (Host) Soft-mode only.
        if self._soft_enabled and self.num_chambers > 0 and self.soft_solver is not None:
            max_delta = self._pressure_rate * self.sim_substeps
            delta = np.clip(
                self.target_pressure - self.current_pressure,
                -max_delta, max_delta,
            )
            self.current_pressure[:] = self.current_pressure + delta
            self.soft_solver.set_chamber_pressures(self.current_pressure.tolist())

        # 4) Substep loop — captured graph if available, eager otherwise.
        # MuJoCo toggle: when off, fall back to eager (the captured
        # graph always includes the rigid solve, so the toggle would
        # be a no-op against it).
        if self.graph is not None and self._mujoco_physics_enabled:
            wp.capture_launch(self.graph)
        else:
            self.simulate()
        self.sim_time += self.frame_dt

        # 5) Stability monitor (mirror-mode default). Reads particle_q
        # after the substep loop completes; checks NaN + max drift
        # from the t=0 rest snapshot for the test_final() assertion.
        if self._stability_check and self._rest_particle_q_np is not None:
            try:
                cur = self.state_0.particle_q.numpy()
                if np.isnan(cur).any():
                    if not self._has_nan:
                        print(f"[soft_gripper_so101] NaN detected at t={self.sim_time:.3f}")
                        self._has_nan = True
                else:
                    drift = float(
                        np.max(np.linalg.norm(cur - self._rest_particle_q_np, axis=1))
                    )
                    self._max_drift = max(self._max_drift, drift)
            except Exception:
                pass

        # 6) Periodic debug dump (off by default; gated by --debug-interval).
        # Streams particle bbox + NaN count + wrist pose + joint_q + chamber
        # pressures so divergence shows up in stdout *before* it goes NaN.
        self._frame_idx += 1
        if self._debug_interval > 0 and self._frame_idx % self._debug_interval == 0:
            self._dump_debug_state()

    def _dump_debug_state(self) -> None:
        """Print one line of position / pose / pressure state to stdout.

        Cheap host-side numpy round-trip. Intended for catching slow
        divergence (drift building up over minutes before the implicit
        solve blows up). Output is one continuous line per call, parsable
        by ``awk`` / ``grep``.
        """
        try:
            parts = [f"[dbg t={self.sim_time:7.3f}s f={self._frame_idx:6d}]"]
            if self._soft_enabled:
                q = self.state_0.particle_q.numpy()
                nan_n = int(np.isnan(q).any(axis=1).sum())
                if nan_n:
                    parts.append(f"NaN={nan_n}/{q.shape[0]}")
                else:
                    qmin = q.min(axis=0)
                    qmax = q.max(axis=0)
                    bbox = qmax - qmin
                    parts.append(
                        "qmin=({:+.3f},{:+.3f},{:+.3f}) qmax=({:+.3f},{:+.3f},{:+.3f}) "
                        "bbox=({:.3f},{:.3f},{:.3f})".format(
                            qmin[0], qmin[1], qmin[2],
                            qmax[0], qmax[1], qmax[2],
                            bbox[0], bbox[1], bbox[2],
                        )
                    )
                    if self._rest_particle_q_np is not None:
                        drift = np.linalg.norm(q - self._rest_particle_q_np, axis=1)
                        parts.append(
                            f"drift max={float(drift.max()):.4f} "
                            f"mean={float(drift.mean()):.4f}"
                        )
                if (
                    self._soft_enabled
                    and self.num_chambers > 0
                    and getattr(self, "current_pressure", None) is not None
                ):
                    p = np.asarray(self.current_pressure)
                    parts.append(f"pres min={float(p.min()):.3f} max={float(p.max()):.3f}")
            if self._arm_enabled:
                try:
                    wrist_tf = self.state_0.body_q.numpy()[self.wrist_body_id]
                    parts.append(
                        "wrist=({:+.3f},{:+.3f},{:+.3f})".format(
                            float(wrist_tf[0]), float(wrist_tf[1]), float(wrist_tf[2])
                        )
                    )
                except Exception:
                    pass
                try:
                    jq = self.state_0.joint_q.numpy()
                    parts.append(
                        "joint_q=[" + ",".join(f"{float(v):+.3f}" for v in jq[: min(8, jq.size)]) + "]"
                    )
                except Exception:
                    pass
            print(" ".join(parts), flush=True)
        except Exception as exc:
            print(f"[soft_gripper_so101][dbg] dump failed: {exc}", flush=True)

    def simulate(self):
        """Pure-device substep loop — captured by :meth:`capture`.

        Must contain only kernel launches and on-device operations:
        any ``.numpy()`` / ``.assign()`` / Python branching on device
        state would either fail under ScopedCapture or silently bake
        a stale value into the graph. In arm mode the cylinder-tip
        transform is recomputed each substep by
        ``_compute_cyl_tip_xform_kernel`` reading ``state_0.body_q``
        directly. In mirror mode that kernel is skipped — the
        ``_cyl_tip_tf_buf`` is populated by host preamble in
        :meth:`step` each frame, and the captured loop just reads it.
        """
        for _ in range(self.sim_substeps):
            self.state_0.clear_forces()
            self.viewer.apply_forces(self.state_0)

            # Soft step. In arm+soft mode the FEM at body_position is
            # spatially separated from the cube/ground so
            # ``model.collide`` registers no soft-rigid pairs. In
            # mirror mode the soft body experiences real gravity and
            # the in-solver ground/contacts come into play.
            if self._soft_enabled and self.soft_solver is not None:
                # Mirror mode reads contacts populated by model.collide;
                # in arm+soft mode the rigid solver also needs contacts,
                # so the collide call below covers both. Mirror mode
                # parity: model.collide BEFORE soft step (matches
                # example_soft_gripper_mirror.py); arm+soft mode runs it
                # AFTER soft step (matches the original so101 pattern).
                # We keep so101's order here — the soft body never
                # touches the rigid scene in arm+soft anyway.
                self.soft_solver.step(
                    self.state_0, self.state_soft, self.control, self.contacts, self.sim_dt
                )
                wp.copy(self.state_0.particle_q, self.state_soft.particle_q)
                wp.copy(self.state_0.particle_qd, self.state_soft.particle_qd)

            # Drive kinematic capsule positions from the deformed FEM.
            # In arm mode the cylinder-tip transform is recomputed
            # on-device each substep so it picks up the latest wrist
            # pose written by the rigid solver below. In mirror mode
            # the transform comes from the host preamble (constant
            # within a frame) — the kernel below is skipped.
            if (
                self._finger_capsules is not None
                and self._finger_spline is not None
                and self._keypoints_world is not None
            ):
                if self._arm_enabled:
                    wp.launch(
                        _compute_cyl_tip_xform_kernel,
                        dim=1,
                        inputs=[
                            self.state_0.body_q,
                            wp.int32(self.wrist_body_id),
                            STEM_TIP_LOCAL,
                            self._body_position_vec,
                            self._cyl_tip_tf_buf,
                        ],
                        device=self.model.device,
                    )
                self._finger_spline.update_world(self.state_0.particle_q)
                wp.launch(
                    _xform_points_by_transform_arr,
                    dim=self._finger_spline.num_keypoints,
                    inputs=[
                        self._finger_spline.keypoint_world,
                        self._cyl_tip_tf_buf,
                        self._keypoints_world,
                    ],
                    device=self.model.device,
                )
                self._finger_capsules.update_endpoints(self._keypoints_world)
                self._finger_capsules.update_kinematic_state(
                    self.state_0, float(self.sim_dt)
                )

            self.model.collide(self.state_0, self.contacts)
            # MuJoCo step is gated by the GUI toggle ONLY on the eager
            # path. The captured graph always replays the rigid step
            # because Python branches don't roll back inside
            # ScopedCapture; ``step()`` falls back to eager when the
            # toggle goes off so the user can still disable physics.
            if self._mujoco_physics_enabled and self.rigid_solver is not None:
                self.rigid_solver.step(
                    self.state_0, self.state_rigid, self.control, self.contacts, self.sim_dt
                )
                wp.copy(self.state_0.body_q, self.state_rigid.body_q)
                wp.copy(self.state_0.body_qd, self.state_rigid.body_qd)
                wp.copy(self.state_0.joint_q, self.state_rigid.joint_q)
                wp.copy(self.state_0.joint_qd, self.state_rigid.joint_qd)

    def capture(self) -> None:
        """Record the substep loop into a CUDA graph for replay.

        Pattern matches example_inflatable_gripper's capture(): snapshot
        every state buffer first so the warmup run doesn't advance the
        sim, run :meth:`simulate` once eagerly to JIT-compile every
        kernel (ScopedCapture chokes if the warp cache is cold),
        restore state, then re-enter inside ``wp.ScopedCapture``. Any
        failure falls back to eager simulation (``self.graph`` stays
        None) instead of crashing.
        """
        self.graph = None
        if not wp.get_device().is_cuda:
            return
        # Snapshot state so the warmup run is fully reversible.
        snaps: dict[str, object] = {}
        for attr in ("state_0", "state_soft", "state_rigid"):
            buf = getattr(self, attr, None)
            if buf is None:
                continue
            snap = self.model.state()
            snap.assign(buf)
            snaps[attr] = snap
        try:
            self.simulate()
            wp.synchronize_device()
        except Exception as exc:
            print(f"   [capture] warmup failed ({exc}); running eager.", flush=True)
            for attr, snap in snaps.items():
                getattr(self, attr).assign(snap)
            return
        for attr, snap in snaps.items():
            getattr(self, attr).assign(snap)
        try:
            with wp.ScopedCapture() as capture:
                self.simulate()
            self.graph = capture.graph
            print("   [capture] CUDA graph recorded — substep loop will replay.", flush=True)
        except Exception as exc:
            print(f"   [capture] ScopedCapture failed ({exc}); running eager.", flush=True)
            for attr, snap in snaps.items():
                getattr(self, attr).assign(snap)
            self.graph = None

        self.sim_time += self.frame_dt

    def _update_joint_frames(self) -> None:
        """Refresh the per-joint X/Y/Z line endpoints from ``state_0.body_q``."""
        if self._joint_frame_starts is None:
            return
        body_q = self.state_0.body_q.numpy()
        n = len(self._joint_frame_body_ids)
        starts = np.zeros((n, 3), dtype=np.float32)
        ends_x = np.zeros((n, 3), dtype=np.float32)
        ends_y = np.zeros((n, 3), dtype=np.float32)
        ends_z = np.zeros((n, 3), dtype=np.float32)
        L = float(self._joint_frame_axis_len)
        for k, body_idx in enumerate(self._joint_frame_body_ids):
            row = body_q[body_idx]
            pos = np.asarray(row[:3], dtype=np.float32)
            qx, qy, qz, qw = float(row[3]), float(row[4]), float(row[5]), float(row[6])
            xx, yy, zz = qx * qx, qy * qy, qz * qz
            xy, xz, yz = qx * qy, qx * qz, qy * qz
            wx, wy, wz = qw * qx, qw * qy, qw * qz
            ax = np.array(
                [1.0 - 2.0 * (yy + zz), 2.0 * (xy + wz), 2.0 * (xz - wy)],
                dtype=np.float32,
            )
            ay = np.array(
                [2.0 * (xy - wz), 1.0 - 2.0 * (xx + zz), 2.0 * (yz + wx)],
                dtype=np.float32,
            )
            az = np.array(
                [2.0 * (xz + wy), 2.0 * (yz - wx), 1.0 - 2.0 * (xx + yy)],
                dtype=np.float32,
            )
            starts[k] = pos
            ends_x[k] = pos + L * ax
            ends_y[k] = pos + L * ay
            ends_z[k] = pos + L * az
        self._joint_frame_starts.assign(starts)
        self._joint_frame_ends_x.assign(ends_x)
        self._joint_frame_ends_y.assign(ends_y)
        self._joint_frame_ends_z.assign(ends_z)

    def render(self):
        self.viewer.begin_frame(self.sim_time)

        if self._arm_enabled:
            # IK gizmo (drag target) only when IK is engaged — when the
            # joint sliders own the control loop, the gizmo would just
            # follow the wrist and confuse the user.
            if self._use_ik:
                self.viewer.log_gizmo("ee_target", self.ee_tf)

            # Stem-tip triad on the gripper body.
            wrist_row = self.state_0.body_q.numpy()[self.wrist_body_id]
            wrist_q = wp.quat(
                float(wrist_row[3]), float(wrist_row[4]),
                float(wrist_row[5]), float(wrist_row[6]),
            )
            wrist_tf = wp.transform(
                wp.vec3(float(wrist_row[0]), float(wrist_row[1]), float(wrist_row[2])),
                wrist_q,
            )
            tip = wp.transform_point(wrist_tf, STEM_TIP_LOCAL)
            L = self._ee_triad_length
            ax = [wp.quat_rotate(wrist_q, wp.vec3(L, 0.0, 0.0)),
                  wp.quat_rotate(wrist_q, wp.vec3(0.0, L, 0.0)),
                  wp.quat_rotate(wrist_q, wp.vec3(0.0, 0.0, L))]
            starts_np = np.tile(
                np.array([float(tip[0]), float(tip[1]), float(tip[2])], dtype=np.float32),
                (3, 1),
            )
            ends_np = np.array(
                [[float(tip[0] + a[0]), float(tip[1] + a[1]), float(tip[2] + a[2])] for a in ax],
                dtype=np.float32,
            )
            self._ee_triad_starts.assign(starts_np)
            self._ee_triad_ends.assign(ends_np)
            self.viewer.log_lines(
                "ee_triad",
                self._ee_triad_starts, self._ee_triad_ends,
                self._ee_triad_colors, width=0.02,
            )

            if self._joint_frame_starts is not None:
                if self._show_joint_frames:
                    self._update_joint_frames()
                self.viewer.log_lines(
                    "joint_frames/x",
                    self._joint_frame_starts, self._joint_frame_ends_x,
                    (1.0, 0.15, 0.15), width=0.02,
                    hidden=not self._show_joint_frames,
                )
                self.viewer.log_lines(
                    "joint_frames/y",
                    self._joint_frame_starts, self._joint_frame_ends_y,
                    (0.15, 1.0, 0.15), width=0.02,
                    hidden=not self._show_joint_frames,
                )
                self.viewer.log_lines(
                    "joint_frames/z",
                    self._joint_frame_starts, self._joint_frame_ends_z,
                    (0.2, 0.4, 1.0), width=0.02,
                    hidden=not self._show_joint_frames,
                )

        # Log everything else (arm + rigid_objects + capsules + soft).
        # In arm+soft mode we then re-log the soft body at the wrist
        # via the cylinder-tip transform; in mirror mode the FEM is
        # already in world coords and log_state handles it directly.
        self.viewer.log_state(self.state_0)

        if (
            self._arm_enabled
            and self._soft_enabled
            and self._soft_particles_world is not None
            and self.model.tri_count > 0
        ):
            # Re-log the soft body's triangle mesh with world-transformed
            # particle positions. The viewer's _shape_to_slot mapping
            # treats the path "/model/triangles" as a known overrideable
            # channel (same trick the standalone inflatable_gripper
            # example uses).
            cylinder_tip_tf = self._current_cylinder_tip_xform()
            wp.launch(
                _xform_points_by_transform,
                dim=int(self.model.particle_count),
                inputs=[
                    self.state_0.particle_q,
                    cylinder_tip_tf,
                    self._soft_particles_world,
                ],
                device=self.model.device,
            )
            self.viewer.log_mesh(
                "/model/triangles",
                self._soft_particles_world,
                self.model.tri_indices.flatten(),
                texture=self._soft_texture,
                hidden=(
                    not self._show_mirror_mesh
                    or not getattr(self.viewer, "show_triangles", True)
                ),
                backface_culling=False,
            )

        # Side mirror: same FEM, re-logged at a translated/rotated copy.
        # In arm+soft mode the mirror is the legacy fixed debug offset
        # (rest orientation, no rotation) gated on ``_show_fem_mesh``.
        # In mirror mode (no-arm + soft) the mirror is the slider-driven
        # 6-DOF pose computed by ``_compute_mirror_transform()``, gated
        # on ``_show_side_mirror``.
        if (
            self._soft_particles_debug is not None
            and self.model.tri_count > 0
        ):
            if self._arm_enabled:
                # Legacy debug mirror — pure translation at a fixed
                # offset, identity rotation.
                debug_tf = wp.transform(
                    wp.vec3(
                        float(self._debug_mirror_position[0]) - self._body_position[0],
                        float(self._debug_mirror_position[1]) - self._body_position[1],
                        float(self._debug_mirror_position[2]) - self._body_position[2],
                    ),
                    wp.quat_identity(),
                )
                hidden = (
                    not self._show_fem_mesh
                    or not getattr(self.viewer, "show_triangles", True)
                )
                texture = self._soft_debug_texture
            else:
                # Mirror mode — 6 DOF slider transform around the
                # mirror hub. The mirror in this mode is the only
                # "interactive" copy (the FEM itself sits at
                # body_position and is the silhouette log_state
                # already draws — undecorated by re-log).
                debug_tf = self._compute_mirror_transform()
                hidden = (
                    not self._show_side_mirror
                    or not getattr(self.viewer, "show_triangles", True)
                )
                texture = self._mirror_texture
            wp.launch(
                _xform_points_by_transform,
                dim=int(self.model.particle_count),
                inputs=[
                    self.state_0.particle_q,
                    debug_tf,
                    self._soft_particles_debug,
                ],
                device=self.model.device,
            )
            self.viewer.log_mesh(
                "/debug/soft_mirror",
                self._soft_particles_debug,
                self.model.tri_indices.flatten(),
                texture=texture,
                hidden=hidden,
                backface_culling=False,
            )

        # Finger-spline + torque-spring overlays (soft mode). The overlays
        # must follow the FEM mesh: in arm+soft mode the mesh is re-logged
        # at the wrist via ``_soft_particles_world``, so the overlays use
        # the same world-transformed particle buffer; in mirror mode the
        # FEM is drawn in place by ``log_state`` and ``state_0.particle_q``
        # is the correct source. Without this branch the overlays sit at
        # the FEM's authoring position (``body_position``) and visually
        # detach from the wrist-mounted mesh.
        overlay_particles = (
            self._soft_particles_world
            if (
                self._arm_enabled
                and self._soft_enabled
                and self._soft_particles_world is not None
            )
            else self.state_0.particle_q
        )
        if self._soft_enabled and self._finger_spline is not None:
            self._finger_spline.update_world(overlay_particles)
            self._finger_spline.log(
                self.viewer,
                line_width=0.005,
                point_radius=0.012,
                hidden=not self._show_finger_spline,
            )
        if self._torque_lines is not None and self._torque_lines.count > 0:
            self._torque_lines.log(
                self.viewer,
                overlay_particles,
                hidden=not self._show_torque_springs,
            )

        self.viewer.end_frame()

    def gui(self, ui) -> None:
        """Mode-aware GUI: arm joint-space controls (arm mode), 6-DOF
        mirror sliders + stability readouts (mirror mode), and per-finger
        pressure sliders (soft mode).
        """
        # Stability readouts (mirror-mode default).
        if self._stability_check:
            ui.text(f"sim_time: {self.sim_time:.2f} s")
            ui.text(f"max particle drift from rest: {self._max_drift:.4f} m")
            if self._has_nan:
                ui.text("STATUS: NaN detected — solver has diverged")
            else:
                ui.text("STATUS: stable")
            if self._soft_enabled:
                ui.text(f"pinned hub particles: {self._num_pinned}")

        if self._arm_enabled:
            changed_ik, value_ik = ui.checkbox("Use IK (drag gizmo)", self._use_ik)
            if changed_ik:
                self._use_ik = bool(value_ik)
            changed_mjc, value_mjc = ui.checkbox(
                "MuJoCo physics (SO-101 + rigid objects)", self._mujoco_physics_enabled,
            )
            if changed_mjc:
                self._mujoco_physics_enabled = bool(value_mjc)
            if self._joint_frame_starts is not None:
                changed_jf, value_jf = ui.checkbox("Show joint frames", self._show_joint_frames)
                if changed_jf:
                    self._show_joint_frames = bool(value_jf)

        if self._arm_enabled and self._soft_enabled:
            # Wrist-tip mirror toggle (the "gripper at the wrist" you
            # see grasping the rigid_objects).
            changed_mir, value_mir = ui.checkbox(
                "Show mirror soft mesh (at wrist)", self._show_mirror_mesh,
            )
            if changed_mir:
                self._show_mirror_mesh = bool(value_mir)
            # FEM-at-body_position debug mirror toggle.
            if self._soft_particles_debug is not None:
                changed_fem, value_fem = ui.checkbox(
                    "Show FEM mesh (far side)", self._show_fem_mesh,
                )
                if changed_fem:
                    self._show_fem_mesh = bool(value_fem)

        # Capsule visibility (soft mode, applies in both arm+soft and
        # mirror+soft).
        if self._capsule_shape_ids:
            changed_cap, value_cap = ui.checkbox(
                f"Show collision capsules ({len(self._capsule_shape_ids)})",
                self._show_capsules,
            )
            if changed_cap:
                self._show_capsules = bool(value_cap)
                self._set_capsules_visible(self._show_capsules)

        if self._soft_enabled and self._finger_spline is not None:
            changed_fs, value_fs = ui.checkbox(
                "Show finger spline", self._show_finger_spline
            )
            if changed_fs:
                self._show_finger_spline = bool(value_fs)

        if self._torque_lines is not None and self._torque_lines.count > 0:
            changed_ts, value_ts = ui.checkbox(
                f"Show torque springs ({self._torque_lines.count})",
                self._show_torque_springs,
            )
            if changed_ts:
                self._show_torque_springs = bool(value_ts)

        # Mirror-mode 6-DOF pose sliders (no-arm + soft only).
        if not self._arm_enabled and self._soft_particles_debug is not None:
            changed_mc, value_mc = ui.checkbox(
                "Show mirror gripper", self._show_side_mirror,
            )
            if changed_mc:
                self._show_side_mirror = bool(value_mc)
            # Translation: ±1 m around the initial slider position.
            p0 = list(self._slider_pos)
            for label, idx in (
                ("mirror pos x", 0), ("mirror pos y", 1), ("mirror pos z", 2),
            ):
                lo = p0[idx] - 1.0
                hi = p0[idx] + 1.0
                changed_p, value_p = ui.slider_float(
                    label, float(self._slider_pos[idx]), lo, hi
                )
                if changed_p:
                    self._slider_pos[idx] = float(value_p)
            # Rotation: ±π radians.
            pi = float(np.pi)
            for label, idx in (
                ("mirror roll", 0), ("mirror pitch", 1), ("mirror yaw", 2)
            ):
                changed_r, value_r = ui.slider_float(
                    label, float(self._slider_euler[idx]), -pi, pi
                )
                if changed_r:
                    self._slider_euler[idx] = float(value_r)

        # Per-joint sliders (arm-only). Only useful when IK is OFF —
        # when IK is on, the gizmo writes the joint targets and these
        # sliders would just track the IK output.
        if self._arm_enabled and not self._use_ik:
            for name in self._joint_names:
                lo, hi = self._safe_joint_limits[name]
                cur = float(self._joint_q_targets[name])
                changed_j, value_j = ui.slider_float(f"joint {name}", cur, lo, hi)
                if changed_j:
                    self._joint_q_targets[name] = float(value_j)

        # Per-finger pressure sliders. In soft mode they drive
        # ``set_chamber_pressures``; in arm-only mode they're
        # placeholders (no solver consumes them).
        if self.num_chambers == 0:
            return
        all_target = float(self.target_pressure.max())
        changed, value = ui.slider_float("all_pressure", all_target, 1.0, self.max_pressure)
        if changed:
            self.target_pressure[:] = float(value)
        for f in self.finger_ids:
            label = f"finger {f}"
            cur = float(np.mean([self.target_pressure[c] for c in self.finger_chambers[f]]))
            changed_f, value_f = ui.slider_float(label, cur, 1.0, self.max_pressure)
            if changed_f:
                for c in self.finger_chambers[f]:
                    self.target_pressure[c] = float(value_f)

    def test_final(self):
        """Stability-aware finalizer.

        When ``stability_check`` is enabled (mirror mode by default) and
        soft mode is on, assert that the soft body did not diverge to
        NaN and that maximum particle drift from the t=0 rest snapshot
        stays under an order-of-magnitude bbox tolerance. Otherwise
        pass.
        """
        if not self._stability_check or self._rest_particle_q_np is None:
            return
        bbox = (
            self._rest_particle_q_np.max(axis=0)
            - self._rest_particle_q_np.min(axis=0)
        )
        tol = 0.5 * float(np.linalg.norm(bbox))
        assert not self._has_nan, "soft body diverged to NaN"
        assert self._max_drift < tol, (
            f"max particle drift {self._max_drift:.4f} m > tolerance {tol:.4f} m"
        )


