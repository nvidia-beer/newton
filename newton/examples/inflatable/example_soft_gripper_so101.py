def _parse_rigid_objects(raw) -> list[dict]:
    """Decode the ``--rigid-objects`` argument into a list of dicts.

    Accepts a JSON string (from CLI / config) or an already-parsed list.
    """
    if raw is None or raw == "":
        return []
    if isinstance(raw, list):
        return list(raw)
    decoded = json.loads(raw)
    if not isinstance(decoded, list):
        raise ValueError(
            f"--rigid-objects must decode to a JSON list, got {type(decoded).__name__}"
        )
    return decoded


def _parse_joints(raw) -> list[dict]:
    """Decode the ``--joints`` argument into a list of joint config dicts."""
    if raw is None or raw == "":
        return []
    if isinstance(raw, list):
        return list(raw)
    decoded = json.loads(raw)
    if not isinstance(decoded, list):
        raise ValueError(
            f"--joints must decode to a JSON list, got {type(decoded).__name__}"
        )
    return decoded


