# Example: Soft-body demo (box | sphere, with optional inflation).
#
# Merged replacement for the four original primitive examples:
#   bouncing_box, bouncing_sphere, inflatable_box, inflatable_sphere.
#
# Loads a tetrahedral FEM primitive (``assets/<shape>/<shape>.usda``,
# generated by ``third_party/newton-mesh-tools``) onto a bouncy ground
# plane and drives it with :class:`newton.solvers.SolverInflatable`. With
# ``--pressure-mode off`` the solver runs at a fixed unit volume ratio
# (plain Neo-Hookean FEM); with ``--pressure-mode on`` a GUI slider drives
# isotropic inflation via :meth:`SolverInflatable.set_pressure` and the
# rest configuration scales by ``cbrt(p)`` each frame.
#
# Command: uv run -m newton.examples inflatable_demo
###########################################################################

